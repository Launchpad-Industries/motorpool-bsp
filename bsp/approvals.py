"""Approvals register: calculated specs a named person has reviewed.

data/approvals.yaml keeps, for each approved MegaMek unit, who approved it,
when, and a snapshot of the values they approved. When a rule change makes
the generator disagree with the snapshot, the unit is flagged as drifted;
the approved values are kept until someone re-approves.

Usage:
    python -m bsp.approvals --mm-data PATH --by Launchpad "Unit full name" ...
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import yaml

from .megamek import Unit, load_all

ROOT = Path(__file__).resolve().parent.parent
FILE = ROOT / "data" / "approvals.yaml"
FIELDS = ("cost", "skill", "mp", "tmm", "range", "damage", "check", "threshold", "specials")


def load(path: Path = FILE) -> dict:
    if not path.exists():
        return {}
    return (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("approvals", {})


def snapshot(sp, skill: int, c: dict) -> dict:
    return {
        "cost": c["regular"] if c["veteran"] is None else f"{c['regular']} ({c['veteran']})",
        "skill": skill,
        "mp": f"{sp.mp}{sp.mode}",
        "tmm": sp.tmm,
        "range": "/".join(map(str, sp.range)) if sp.range else "-",
        "damage": f"{sp.damage[0]}x{sp.damage[1]}" if sp.damage and sp.damage[1] > 1
                  else (str(sp.damage[0]) if sp.damage else "-"),
        "check": sp.check,
        "threshold": sp.threshold,
        "specials": ", ".join(sorted(set(sp.specials))) or "-",
    }


def drift(entry: dict, current: dict) -> list[str]:
    """Fields where the generator no longer gives the approved value."""
    approved = entry.get("values", {})
    return [k for k in FIELDS if k in approved and str(approved[k]) != str(current[k])]


def label(entry: dict) -> str:
    return f"Autogenerated-Approved by {entry['by']}"


def approve(units: list[Unit], weapons: dict, by: str, note: str = "") -> dict:
    from .generate import spec_for
    data = {"approvals": load()}
    for u in units:
        sp, skill, c = spec_for(u, weapons)
        data["approvals"][u.full_name] = {
            "by": by, "on": date.today().isoformat(),
            "values": snapshot(sp, skill, c),
            **({"note": note} if note else {}),
        }
    header = ("# Calculated specs approved by a named reviewer, with the values\n"
              "# approved. Written by `python -m bsp.approvals`; the generator flags\n"
              "# drift when a rule change disagrees with these values.\n")
    FILE.write_text(header + yaml.safe_dump(data, sort_keys=True, allow_unicode=True),
                    encoding="utf-8")
    return data["approvals"]


def main(argv=None):
    ap = argparse.ArgumentParser(description="Record approval of calculated specs")
    ap.add_argument("--mm-data", required=True, type=Path)
    ap.add_argument("--by", required=True)
    ap.add_argument("--note", default="")
    ap.add_argument("units", nargs="+", help="MegaMek unit full names")
    a = ap.parse_args(argv)
    weapons = json.loads((ROOT / "cache" / "weapons.json").read_text())
    pool = {u.full_name: u for u in load_all(a.mm_data, folders=("vehicles",))}
    missing = [n for n in a.units if n not in pool]
    if missing:
        raise SystemExit(f"Not found in MegaMek data: {missing}")
    approve([pool[n] for n in a.units], weapons, a.by, a.note)
    print(f"Approved {len(a.units)} unit(s) by {a.by} -> {FILE}")


if __name__ == "__main__":
    main()
