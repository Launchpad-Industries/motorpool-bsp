"""Approvals register: calculated specs a named person has reviewed.

Each approval keeps who approved it, when, the generator's values at the
time (``values``, used to flag drift when a rule change disagrees), and the
card as approved (``card``), which may include hand tweaks (``changes``) and a
cost override. Approved cards print with their approved values.

Two stores:
- ``data/approvals.yaml`` (in the repository): approvals signed by a trusted
  key, i.e. the owner's (see bsp/signing.py). These show as verified.
- ``~/.motorpool/approvals.yaml``: approvals made on a machine without a
  trusted key (e.g. a friend's), under that person's name, unverified.

Usage:
    python -m bsp.approvals --mm-data PATH --by Launchpad "Unit full name" ...
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import yaml

from . import signing
from .megamek import Unit, load_all

ROOT = Path(__file__).resolve().parent.parent
FILE = ROOT / "data" / "approvals.yaml"
LOCAL_FILE = signing.HOME / "approvals.yaml"
FIELDS = ("cost", "skill", "mp", "tmm", "range", "damage", "check", "threshold", "specials")
HEADER = ("# Calculated specs approved by a named reviewer. `values` are the\n"
          "# generator's values when approved (drift is flagged when the rules\n"
          "# change); `card` is the card as approved, including any tweaks.\n"
          "# Entries signed with a trusted key (data/trusted_keys.yaml) are verified.\n")


def _read(path: Path) -> dict:
    if not path.exists():
        return {}
    return (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("approvals", {}) or {}


def _write(path: Path, entries: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + yaml.safe_dump({"approvals": entries}, sort_keys=True,
                                            allow_unicode=True), encoding="utf-8")


def load(path: Path | None = None, local: Path | None = LOCAL_FILE) -> dict:
    """All approvals by unit full name, each with ``verified`` set.
    A verified repository approval beats a local one; otherwise the local
    (more recent, this machine's) approval wins."""
    keys = signing.trusted_keys()
    out = {}
    for name, e in _read(path or FILE).items():
        out[name] = dict(e, verified=signing.verify(e, keys), store="repo")
    if local is not None:
        for name, e in _read(local).items():
            if name in out and out[name]["verified"]:
                continue
            out[name] = dict(e, verified=signing.verify(e, keys), store="local")
    return out


def snapshot(sp, skill: int, c: dict) -> dict:
    return {
        "cost": c["regular"] if c["veteran"] is None else f"{c['regular']} ({c['veteran']})",
        "skill": skill,
        "mp": f"{sp.mp}{sp.mode}",
        "tmm": sp.tmm,
        "range": "/".join(map(str, sp.range)) if sp.range else "-",
        "damage": f"{sp.damage[0]}x{sp.damage[1]}" if sp.damage and sp.damage[1] > 1
                  else (str(sp.damage[0]) if sp.damage else "-"),
        "check": sp.check,
        "threshold": sp.threshold,
        "specials": ", ".join(sorted(set(sp.specials))) or "-",
    }


def drift(entry: dict, current: dict) -> list[str]:
    """Fields where the generator no longer gives the value it gave at approval."""
    approved = entry.get("values", {})
    return [k for k in FIELDS if k in approved and str(approved[k]) != str(current[k])]


def label(entry: dict) -> str:
    return f"Autogenerated-Approved by {entry['by']}" + ("" if entry.get("verified") else " (unverified)")


def record(unit_name: str, values: dict, card: dict, by: str, changes: dict | None = None,
           cost_override: bool = False, note: str = "") -> dict:
    """Store an approval. Signed into the repository when this machine holds
    the trusted key for ``by``; otherwise saved locally, unverified."""
    entry = {"by": by, "on": date.today().isoformat(), "values": values, "card": card}
    if changes:
        entry["changes"] = changes
    if cost_override:
        entry["cost_override"] = True
    if note:
        entry["note"] = note
    key = signing.load_private()
    if key is not None and signing.owner_name(key) == by:
        entry["sig"] = signing.sign(entry, key)
        path = FILE
    else:
        path = LOCAL_FILE
    entries = _read(path)
    entries[unit_name] = entry
    _write(path, entries)
    return dict(entry, verified="sig" in entry, store="repo" if path == FILE else "local")


def withdraw(unit_name: str) -> bool:
    for path in (LOCAL_FILE, FILE):
        entries = _read(path)
        if unit_name in entries:
            del entries[unit_name]
            _write(path, entries)
            return True
    return False


def sign_existing() -> int:
    """Sign repository approvals made under this machine's trusted name."""
    key = signing.load_private()
    name = signing.owner_name(key)
    if not name:
        raise SystemExit("No trusted signing key on this machine (run: python -m bsp.signing init --name NAME)")
    entries, n = _read(FILE), 0
    for e in entries.values():
        if e.get("by") == name and not signing.verify(e):
            e.pop("sig", None)
            e["sig"] = signing.sign(e, key)
            n += 1
    _write(FILE, entries)
    return n


def approve(units: list[Unit], weapons: dict, by: str, note: str = "") -> dict:
    """Approve units as generated (command line)."""
    from .art import Art
    from .cards import card_from_unit, card_values
    from .generate import spec_for
    out = {}
    for u in units:
        sp, skill, c = spec_for(u, weapons)
        card = card_from_unit(u, weapons, Art(), {})
        out[u.full_name] = record(u.full_name, snapshot(sp, skill, c), card_values(card), by,
                                  note=note)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description="Record approval of calculated specs")
    ap.add_argument("--mm-data", required=True, type=Path)
    ap.add_argument("--by", required=True)
    ap.add_argument("--note", default="")
    ap.add_argument("units", nargs="+", help="MegaMek unit full names")
    a = ap.parse_args(argv)
    weapons = json.loads((ROOT / "cache" / "weapons.json").read_text())
    pool = {u.full_name: u for u in load_all(a.mm_data, folders=("vehicles",))}
    missing = [n for n in a.units if n not in pool]
    if missing:
        raise SystemExit(f"Not found in MegaMek data: {missing}")
    res = approve([pool[n] for n in a.units], weapons, a.by, a.note)
    where = {e["store"] for e in res.values()}
    print(f"Approved {len(a.units)} unit(s) by {a.by} ({', '.join(sorted(where))} store)")


if __name__ == "__main__":
    main()
